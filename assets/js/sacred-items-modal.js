/**
 * Sacred Items Modal Module
 * Handles zoom modal, navigation, image flipping, and swipe gestures for sacred items.
 *
 * Architecture:
 * - Modal displays one sacred item at a time
 * - Supports front/back image flipping
 * - Keyboard and swipe navigation (Arrow keys, Up/Down swipes)
 * - Maintains state of all sacred items indexed by carousel-manager
 */

(function(window) {
  'use strict';

  class SacredItemsModal {
    constructor(options = {}) {
      this.modalSelector = options.modalSelector || '#sacredItemModal';
      this.containerSelector = options.containerSelector || '#qurbanaCarousel';
      this.modal = document.querySelector(this.modalSelector);
      this.container = document.querySelector(this.containerSelector);

      this.carouselManager = window.carouselManager;
      this.currentSacredItems = [];
      this.currentItemIndex = 0;
      this.swipeDetector = null;

      this.init();
    }

    init() {
      if (!this.modal || !this.container) {
        console.error('Modal or container not found');
        return;
      }

      this.setupSwipeDetector();
      this.setupKeyboardNavigation();
      this.setupEventDelegation();
    }

    // ========================================================================
    // Item Discovery & Indexing
    // ========================================================================

    discoverSacredItems() {
      this.currentSacredItems = [];
      const stage = this.carouselManager.getCurrentStage();
      if (!stage) return;

      const substagesArray = stage.substages || [stage];
      substagesArray.forEach(substage => {
        (substage.sacred_items || []).forEach(item => {
          this.currentSacredItems.push(item);
        });
      });
    }

    // ========================================================================
    // Modal Display
    // ========================================================================

    openModal(itemName) {
      this.discoverSacredItems();

      // Find item by name
      const itemIndex = this.currentSacredItems.findIndex(
        item => item.name.toLowerCase() === itemName.toLowerCase()
      );

      if (itemIndex === -1) {
        console.warn('Sacred item not found:', itemName);
        return;
      }

      this.currentItemIndex = itemIndex;
      this.displayCurrentItem();
      this.modal.classList.add('visible');
      document.body.style.overflow = 'hidden';
    }

    closeModal() {
      this.modal.classList.remove('visible');
      document.body.style.overflow = '';
    }

    displayCurrentItem() {
      const item = this.currentSacredItems[this.currentItemIndex];
      if (!item) return;

      const utils = window.CarouselUtils;

      // Image and flip button
      const imageEl = this.modal.querySelector('#modalSacredItemImage');
      if (imageEl) {
        imageEl.dataset.front = utils.toWebP(item.image || '');
        imageEl.dataset.back = utils.toWebP(item.back_image || '');
        imageEl.dataset.current = 'front';
        imageEl.src = imageEl.dataset.front;
        imageEl.alt = item.name;
      }

      const flipBtn = this.modal.querySelector('#modalFlipButton');
      if (flipBtn) {
        flipBtn.style.display = item.back_image ? 'block' : 'none';
      }

      // Item counter
      this.updateItemCounter();

      // Item details (safe text content)
      this.updateItemDetails(item);

      // Navigation arrows visibility
      this.updateNavigationArrows();

      // Swipe hints
      this.updateSwipeHints();
    }

    updateItemDetails(item) {
      const nameEl = this.modal.querySelector('#modalSacredItemName');
      const malayalamEl = this.modal.querySelector('#modalSacredItemMalayalam');
      const meaningEl = this.modal.querySelector('#modalSacredItemMeaning');
      const historicalEl = this.modal.querySelector('#modalSacredItemHistorical');
      const biblicalEl = this.modal.querySelector('#modalSacredItemBiblical');

      if (nameEl) nameEl.textContent = item.name || '';
      if (malayalamEl) malayalamEl.textContent = item.malayalam || '';

      // Theological meaning with linked bible references (safe: generated by linkBibleRefs)
      if (meaningEl) {
        const linked = window.CarouselUtils.linkBibleRefs(item.meaning || '');
        // Note: linkBibleRefs generates safe HTML with properly escaped URL parameters
        meaningEl.innerHTML = linked;
      }

      // Historical context (safe: from YAML front matter, written by page author)
      if (item.historical_context) {
        if (historicalEl) {
          historicalEl.style.display = 'block';
          const textEl = historicalEl.querySelector('.sacred-item-modal-text');
          if (textEl) {
            // Safe: page author writes this in YAML, not external input
            textEl.innerHTML = item.historical_context;
          }
        }
      } else if (historicalEl) {
        historicalEl.style.display = 'none';
      }

      // Biblical reference (safe: from YAML front matter, written by page author)
      if (item.biblical_reference) {
        if (biblicalEl) {
          biblicalEl.style.display = 'block';
          const textEl = biblicalEl.querySelector('.sacred-item-modal-text');
          if (textEl) {
            // Safe: page author writes this in YAML, not external input
            textEl.innerHTML = item.biblical_reference;
          }
        }
      } else if (biblicalEl) {
        biblicalEl.style.display = 'none';
      }
    }

    updateItemCounter() {
      const currentNum = this.modal.querySelector('#currentItemNum');
      const totalNum = this.modal.querySelector('#totalItemsNum');
      if (currentNum) currentNum.textContent = this.currentItemIndex + 1;
      if (totalNum) totalNum.textContent = this.currentSacredItems.length;
    }

    updateNavigationArrows() {
      const prevArrow = this.modal.querySelector('#modalPrevArrow');
      const nextArrow = this.modal.querySelector('#modalNextArrow');

      if (prevArrow) {
        prevArrow.style.display = this.currentItemIndex > 0 ? 'block' : 'none';
      }
      if (nextArrow) {
        nextArrow.style.display = this.currentItemIndex < this.currentSacredItems.length - 1 ? 'block' : 'none';
      }
    }

    updateSwipeHints() {
      const hintUp = this.modal.querySelector('#swipeHintTop');
      const hintDown = this.modal.querySelector('#swipeHintBottom');

      if (hintUp) {
        hintUp.style.display = this.currentItemIndex < this.currentSacredItems.length - 1 ? 'flex' : 'none';
      }
      if (hintDown) {
        hintDown.style.display = this.currentItemIndex > 0 ? 'flex' : 'none';
      }
    }

    // ========================================================================
    // Navigation
    // ========================================================================

    nextItem() {
      if (this.currentItemIndex < this.currentSacredItems.length - 1) {
        this.currentItemIndex++;
        this.displayCurrentItem();
      }
    }

    prevItem() {
      if (this.currentItemIndex > 0) {
        this.currentItemIndex--;
        this.displayCurrentItem();
      }
    }

    flipImage() {
      const imageEl = this.modal.querySelector('#modalSacredItemImage');
      const labelEl = this.modal.querySelector('#modalViewLabel');
      if (!imageEl) return;

      const current = imageEl.dataset.current;
      const newSide = current === 'front' ? 'back' : 'front';
      const newSrc = imageEl.dataset[newSide];

      if (newSrc) {
        imageEl.src = newSrc;
        imageEl.dataset.current = newSide;
        if (labelEl) {
          labelEl.textContent = newSide === 'front' ? 'Front View' : 'Back View';
        }
      }
    }

    // ========================================================================
    // Gesture Handling
    // ========================================================================

    setupSwipeDetector() {
      this.swipeDetector = new window.CarouselUtils.SwipeDetector(this.modal);
      this.swipeDetector.on('Up', () => this.nextItem());
      this.swipeDetector.on('Down', () => this.prevItem());
    }

    setupKeyboardNavigation() {
      document.addEventListener('keydown', (e) => {
        if (!this.modal.classList.contains('visible')) return;

        if (e.key === 'ArrowDown' || e.key === 'ArrowRight') {
          this.nextItem();
        } else if (e.key === 'ArrowUp' || e.key === 'ArrowLeft') {
          this.prevItem();
        } else if (e.key === 'Escape') {
          this.closeModal();
        }
      });
    }

    // ========================================================================
    // Event Delegation
    // ========================================================================

    setupEventDelegation() {
      // Close button
      const closeBtn = this.modal.querySelector('.sacred-item-modal-close');
      if (closeBtn) {
        closeBtn.addEventListener('click', () => this.closeModal());
      }

      // Previous/Next arrows
      const prevArrow = this.modal.querySelector('#modalPrevArrow');
      const nextArrow = this.modal.querySelector('#modalNextArrow');
      if (prevArrow) {
        prevArrow.addEventListener('click', () => this.prevItem());
      }
      if (nextArrow) {
        nextArrow.addEventListener('click', () => this.nextItem());
      }

      // Flip button
      const flipBtn = this.modal.querySelector('#modalFlipButton');
      if (flipBtn) {
        flipBtn.addEventListener('click', () => this.flipImage());
      }

      // Close on backdrop click
      this.modal.addEventListener('click', (e) => {
        if (e.target === this.modal) {
          this.closeModal();
        }
      });
    }
  }

  // Export
  window.SacredItemsModal = SacredItemsModal;

})(window);
